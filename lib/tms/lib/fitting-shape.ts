//
// ⚠️ ອ່ານກ່ອນໃຊ້: ເລກຢູ່ນີ້ **ບໍ່ແມ່ນ** ຕົວເລກຈາກ catalogue ຂອງ SCG ຫຼື
// ຜູ້ຜະລິດໃດ. ມັນຄິດມາຈາກຄວາມສຳພັນເລຂາຄະນິດທີ່ ມອກ.1131 ກຳນົດ: ຮ່ອງຮັບທໍ່
// ຕ້ອງເລິກ ແລະ ໜາຕາມສ່ວນຂອງ OD ທໍ່ ສະນັ້ນຂໍ້ຕໍ່ທຸກຂະໜາດຈຶ່ງເປັນຮູບຊົງຄືກັນ
// ແລະ ຂອບເຂດຂອງມັນຂະຫຍາຍຕາມ OD³.
//
//   ປະລິມານກ່ອງຫຸ້ມ ≈ k × OD³     (k = ຕົວຄູນຮູບຊົງ ຕໍ່ປະເພດຂໍ້ຕໍ່)
//
// ຕົວຄູນ k ຂ້າງລຸ່ມແມ່ນການປະມານທາງວິສະວະກຳ ບໍ່ແມ່ນເລກທີ່ພິມເຜີຍແພ່ —
// ຄາດວ່າຜິດພາດໄດ້ ±40%. ໃຊ້ເປັນ "ຈຸດຕັ້ງຕົ້ນ" ເທົ່ານັ້ນ: ພໍວັດ 1 ຫີບຂອງ
// ຕະກຸນໃດ ຄ່າວັດຈິງຈະທັບຄ່ານີ້ທັນທີ (ເບິ່ງ pack-resolve.ts).

export interface FittingShape {
  /** ຄຳທີ່ຕ້ອງພົບໃນຊື່ຕະກຸນ — ກວດຕາມລຳດັບ ອັນສະເພາະກວ່າມາກ່ອນ */
  match: string[];
  /** k ໃນສູດ ປະລິມານ ≈ k × OD³ */
  k: number;
  label: string;
}

/**
 * ລຳດັບສຳຄັນ: "ຂໍ້ງໍ 45" ຕ້ອງກວດກ່ອນ "ຂໍ້ງໍ" ບໍ່ດັ່ງນັ້ນຈະຖືກຈັບເປັນ 90°.
 */
export const FITTING_SHAPES: FittingShape[] = [
  // ຂໍ້ງໍ 45° — ສັ້ນກວ່າ 90° ເພາະແຂນງໍໜ້ອຍ
  { match: ["ຂໍ້ງໍ", "45"], k: 2.6, label: "ຂໍ້ງໍ 45°" },
  // ຂໍ້ງໍ 90° — ກ່ອງ ≈ (1.1D + ຮັດສະໝີຮ່ອງ)² × OD ຮ່ອງ
  { match: ["ຂໍ້ງໍ"], k: 3.7, label: "ຂໍ້ງໍ 90°" },
  // ສາມຕາ — ມີແຂນທີ່ 3 ຈຶ່ງກວ້າງກວ່າຂໍ້ງໍ
  { match: ["ສາມຕາ"], k: 4.7, label: "ສາມຕາ" },
  // ຂໍ້ຕໍ່ລົດ / ຫຼຸດຂະໜາດ — ໃຊ້ຂ້າງໃຫຍ່ເປັນ D
  { match: ["ຂໍ້ຕໍ່ລົດ"], k: 3.1, label: "ຂໍ້ຕໍ່ລົດ" },
  // ຂໍ້ຕໍ່ຊື່ / ຂໍ້ຕໍ່ເຂົ້າກ່ອງ — ກະບອກສັ້ນ
  { match: ["ຂໍ້ຕໍ່"], k: 3.6, label: "ຂໍ້ຕໍ່ຊື່" },
  // ຝາຄອບ / ປັກອຸດ — ປິດປາຍ ສັ້ນສຸດ
  { match: ["ຝາຄອບ"], k: 1.9, label: "ຝາຄອບ" },
  { match: ["ປັກອຸດ"], k: 1.9, label: "ປັກອຸດ" },
  // ກິບຮັດ / ແຮງເກີ້ — ບາງ ບໍ່ຫຸ້ມຮອບ
  { match: ["ກິບຮັດ"], k: 1.3, label: "ກິບຮັດ" },
  { match: ["ກິບ"], k: 1.3, label: "ກິບ" },
  { match: ["ແຮງເກີ້"], k: 1.8, label: "ແຮງເກີ້" },
  // ປະຕູນ້ຳ / ວາວ — ມີມືໝູນ ຈຶ່ງໃຫຍ່ກວ່າຂໍ້ຕໍ່ຫຼາຍ
  { match: ["ປະຕູນ້ຳ"], k: 8.0, label: "ປະຕູນ້ຳ" },
];

/** ຫາຕົວຄູນຮູບຊົງຂອງຕະກຸນ — null ເມື່ອບໍ່ຮູ້ຈັກ (ຢ່າເດົາ) */
export function findFittingShape(family: string | null | undefined): FittingShape | null {
  const name = String(family ?? "");
  if (!name) return null;
  for (const shape of FITTING_SHAPES) {
    if (shape.match.every((token) => name.includes(token))) return shape;
  }
  return null;
}

/**
 * ປະລິມານກ່ອງຫຸ້ມຂອງຂໍ້ຕໍ່ 1 ຕົວ (m³) ຈາກ OD ຂອງທໍ່ (mm).
 * ຄືນ null ເມື່ອຂາດຂໍ້ມູນ — ບໍ່ເດົາ.
 */
export function fittingPieceM3(
  odMm: number | null | undefined,
  shape: FittingShape | null
): number | null {
  const od = Number(odMm);
  if (!shape || !Number.isFinite(od) || od <= 0) return null;
  const odM = od / 1000;
  return shape.k * odM * odM * odM;
}
